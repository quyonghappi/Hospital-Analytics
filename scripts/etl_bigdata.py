from google.cloud import storage
client = storage.Client()

bucket = client.bucket(
    "project-8e2366a6-d3cc-40ee-9de-bronze-raw-dev"
)
blobs = bucket.list_blobs(
    prefix="cms/pos/"
)

parquet_files = [

    blob.name

    for blob in blobs

    if blob.name.endswith(".parquet")
]

for f in parquet_files[:5]:
    print(f)

silver_path = (
    "gs://project-8e2366a6-d3cc-40ee-9de-silver-curated-dev/"
    "cms/pos/"
)

import re

for file_path in parquet_files:

    # =====================================
    # extract year + quarter
    # =====================================

    match = re.search(
        r"cms_pos_(q[1-4])_(\d{4})",
        file_path
    )

    if not match:
        print(f"Skip invalid filename: {file_path}")
        continue

    quarter = match.group(1).upper()
    year = int(match.group(2))

    print(f"\nProcessing {year} {quarter}")

    # =====================================
    # read bronze parquet
    # =====================================

    gcs_path = (
        "gs://project-8e2366a6-d3cc-40ee-9de-bronze-raw-dev/"
        + file_path
    )

    df_raw = spark.read.parquet(gcs_path)

    print(f"Raw rows: {df_raw.count()}")

    # =====================================
    # ETL
    # =====================================

    df_silver = (

        df_raw

        .select(

            col("PRVDR_NUM").alias("provider_id"),

            col("FAC_NAME").alias("facility_name"),

            col("CITY_NAME").alias("city"),

            col("STATE_CD").alias("state"),

            col("ZIP_CD").alias("zip_code"),

            col("FIPS_CNTY_CD").alias(
                "fips_county_code"
            ),

            col("CRTFD_BED_CNT").alias(
                "certified_bed_count"
            ),

            col("GNRL_FAC_TYPE_CD").alias(
                "facility_type_code"
            )
        )
    )

    # =====================================
    # clean text
    # =====================================

    TEXT_COLS = [

        "facility_name",
        "city",
        "state"
    ]

    for c in TEXT_COLS:

        df_silver = df_silver.withColumn(
            c,
            upper(trim(col(c)))
        )

    # =====================================
    # cast datatype
    # =====================================

    df_silver = df_silver.withColumn(

    "certified_bed_count",

    when(
        trim(col("certified_bed_count")) == "",
        None
    )

    .otherwise(
        col("certified_bed_count")
    )

    .cast(IntegerType())
)

    # =====================================
    # dedup
    # =====================================

    df_silver = df_silver.dropDuplicates()

    # =====================================
    # metadata
    # =====================================

    df_silver = (

        df_silver

        .withColumn(
            "_source",
            lit("cms_pos")
        )

        .withColumn(
            "_processed_at",
            current_timestamp()
        )

        .withColumn(
            "year",
            lit(year)
        )

        .withColumn(
            "quarter",
            lit(str(quarter))
        )
    )

    # =====================================
    # repartition
    # =====================================

    df_silver = df_silver.repartition(
        "year",
        "quarter"
    )

    print(f"Silver rows: {df_silver.count()}")

    # =====================================
    # write silver
    # =====================================

    (
        df_silver

        .write

        .mode("append")

        .partitionBy("year", "quarter")

        .parquet(silver_path)
    )

    print(f"Done {year} {quarter}")

df_silver.printSchema()

