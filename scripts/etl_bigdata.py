    # facility info
    # =========================

    col("hospital_name").alias("facility_name"),

    col("address"),

    col("city"),

    col("state"),

    col("zip").alias("zip_code"),

    col("fips_code").alias("fips_county_code"),

    col("hospital_subtype"),

    col("is_metro_micro"),

    # =========================
    # date
    # =========================

    col("collection_week").alias("report_date"),

    # =========================
    # inpatient metrics
    # =========================

    col("total_beds_7_day_avg").alias(
        "inpatient_beds_total"
    ),

    col("inpatient_beds_used_7_day_avg").alias(
        "inpatient_beds_used"
    ),

    # =========================
    # ICU metrics
    # =========================

    col("total_icu_beds_7_day_avg").alias(
        "icu_beds_total"
    ),

    col("icu_beds_used_7_day_avg").alias(
        "icu_beds_used"
    ),

    # =========================
    # COVID metrics
    # =========================

