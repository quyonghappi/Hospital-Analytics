def preprocessing(df_silver):

    numeric_cols = df_silver.select_dtypes(
        exclude=['object']
    ).columns

    for col in numeric_cols:

        df_silver[col] = (
            df_silver[col]
            .astype(str)
            .str.strip()
            .str.replace(',', '', regex=False)
            .str.replace(r'[^0-9.\-]', '', regex=True)
        )

        df_silver[col] = pd.to_numeric(
            df_silver[col],
            errors='coerce'
        ).astype(float)

    return df_silver

