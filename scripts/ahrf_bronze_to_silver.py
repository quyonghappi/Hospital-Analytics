import re

def convert_sas_to_asc(sas_file_path, asc_file_path):
    colspecs = []
    names = []

    with open(sas_file_path , 'r', encoding='latin1') as f:
        lines = f.readlines()

    for line in lines:
        match = re.search(r'@(\d+)\s+(\w+)\s+\$?(\d+)\.', line)

        if match:
            start = int(match.group(1))
            name = match.group(2)
            width = int(match.group(3))

            colspecs.append((start-1, start-1+width))
            names.append(name)

    df = pd.read_fwf(
        asc_file_path,
        colspecs=colspecs,
        names=names,
        encoding = 'latin1'
    )

    return df

