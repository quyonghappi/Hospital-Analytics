def drop_high_null_columns(df, threshold=80):
    """
    Drop các cột có tỷ lệ null > threshold (%)
    """

    # Tính % null theo cột
    null_percent = df.isnull().mean() *100

    # In ra để kiểm tra
    print("Tỷ lệ null theo cột:")
    print(null_percent.sort_values(ascending=False))

    # Lấy danh sách cột cần drop
    cols_to_drop = null_percent[null_percent > threshold].index

    print(f"\nCác cột bị drop (> {threshold}% null):")
    print(list(cols_to_drop))

    # Drop cột
    df = df.drop(columns=cols_to_drop)

    return df

